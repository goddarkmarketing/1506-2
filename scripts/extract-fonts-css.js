// Pulls the @font-face rules and --font-* variables out of the scraped homepage
// into css/dg-fonts.css so the generated region pages can use the same typefaces.
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const html = fs.readFileSync(path.join(root, "index.html"), "utf8");

// Only look inside <style> blocks.
const css = [...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)]
  .map((m) => m[1])
  .join("\n");

const faces = [...css.matchAll(/@font-face\s*\{[^}]*\}/g)].map((m) => m[0]);
const varRules = [...css.matchAll(/\.[a-zA-Z0-9_-]+__variable\s*\{[^}]*\}/g)].map((m) => m[0]);

if (!faces.length) throw new Error("no @font-face rules found in index.html");

// url(fonts/x.woff2) -> url(../fonts/x.woff2) because the stylesheet lives in css/
const rebase = (rule) =>
  rule.replace(/url\((["']?)(?:\.\/)?fonts\//g, "url($1../fonts/");

// The module classes look like `.poppins_x-module__y__variable{--font-poppins:...}`.
// Re-publish those custom properties on :root so any page can use them.
const rootVars = [];
for (const rule of varRules) {
  const body = rule.slice(rule.indexOf("{") + 1, rule.lastIndexOf("}"));
  body
    .split(";")
    .map((d) => d.trim())
    .filter((d) => d.startsWith("--font-"))
    .forEach((d) => rootVars.push(d));
}

const out = [
  "/* Generated by scripts/extract-fonts-css.js — do not edit by hand. */",
  "/* Same webfonts as the scraped pages, so shared chrome renders identically. */",
  "",
  faces.map(rebase).join("\n"),
  "",
  ":root {",
  ...[...new Set(rootVars)].map((d) => "  " + d + ";"),
  // index.html resolves body text through --font-sans.
  "  --font-sans: var(--font-geist-sans);",
  "}",
  "",
].join("\n");

const outFile = path.join(root, "css", "dg-fonts.css");
fs.writeFileSync(outFile, out, "utf8");

// Every referenced font file must exist next to the stylesheet.
const missing = [...new Set([...out.matchAll(/url\(["']?([^"')]+)["']?\)/g)].map((m) => m[1]))]
  .filter((u) => !/^(data:|https?:)/.test(u))
  .filter((u) => !fs.existsSync(path.resolve(path.dirname(outFile), u)));

console.log("font-face rules:", faces.length);
console.log("font variables:", [...new Set(rootVars)].length);
if (missing.length) console.log("MISSING FONT FILES:", missing.join(", "));
else console.log("all referenced font files exist");
